/**
 * Builds a tiny static "forwarding" site for the OLD domain (www.portugal-shipowners.com),
 * so every old link (Google, press articles, bookmarks) lands on the right page of www.maritime.pt.
 *
 *   npm run legacy:build   ->  writes ./legacy-site/
 *
 * Publish ./legacy-site/ as its own GitHub Pages repo (see README, step 22).
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const NEW = 'https://www.maritime.pt';
const OLD_HOST = 'www.portugal-shipowners.com';
const OUT = 'legacy-site';

const rules = readFileSync('public/_redirects', 'utf8')
  .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split(/\s+/)).map(([from, to]) => [from, to]);

const page = (to) => `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>EISAP has moved to maritime.pt</title>
<meta http-equiv="refresh" content="0;url=${to}">
<link rel="canonical" href="${to}"><meta name="robots" content="noindex">
<script>location.replace(${JSON.stringify(to)});</script></head>
<body style="font-family:system-ui,sans-serif;padding:40px">EISAP has moved to <a href="${to}">${to}</a>.</body></html>\n`;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// Known old pages -> exact new page
for (const [from, to] of rules) {
  const dir = join(OUT, from.replace(/^\//, ''));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), page(NEW + to));
}
// Home
writeFileSync(join(OUT, 'index.html'), page(NEW + '/'));
// Anything else (old PDFs, unknown pages) -> same path on the new site if it exists, otherwise home
writeFileSync(join(OUT, '404.html'), `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>EISAP has moved to maritime.pt</title><meta name="robots" content="noindex">
<script>
  var p = location.pathname;
  var known = /^\\/(about|events|news|governance|membership|contact|members|privacy|cookies|legal-notice)(\\/|$)/.test(p);
  location.replace(${JSON.stringify(NEW)} + (known ? p : '/'));
</script></head>
<body style="font-family:system-ui,sans-serif;padding:40px">EISAP has moved to <a href="${NEW}/">${NEW}</a>.</body></html>\n`);
writeFileSync(join(OUT, 'CNAME'), OLD_HOST + '\n');
writeFileSync(join(OUT, 'robots.txt'), 'User-agent: *\nAllow: /\n');
writeFileSync(join(OUT, 'README.md'), `# portugal-shipowners.com → maritime.pt\n\nForwarding site for the old EISAP domain. Generated by \`npm run legacy:build\` in the main website repo — do not edit by hand.\n`);
console.log(`Legacy forwarding site written to ./${OUT} (${rules.length} mapped URLs)`);
